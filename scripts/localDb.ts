/**
 * Local Tables feature, server side (docs/local-tables.md): the pure parts, so they can be
 * tested without a database. scripts/viteLocalDb.ts runs them against the local stack.
 *
 * Every table and column name used in SQL is checked against the catalogue first and
 * double-quoted; every value goes in as a bind parameter.
 *
 * Destination: scripts/localDb.ts
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

export interface ColumnMeta {
  name: string
  type: string
  notnull: boolean
  generated: boolean
  pk: boolean
}

export interface TableMeta {
  name: string
  /** r table, p partitioned table, v view, m materialized view */
  kind: 'r' | 'p' | 'v' | 'm'
  estimate: number
  comment: string | null
  columns: ColumnMeta[]
}

/** Catalogue of the public schema: tables, views and materialized views with their columns. */
export const META_SQL = `
select c.relname as name, c.relkind as kind, greatest(c.reltuples, 0)::bigint as estimate,
       obj_description(c.oid, 'pg_class') as comment,
       coalesce((
         select json_agg(json_build_object(
                  'name', a.attname,
                  'type', format_type(a.atttypid, a.atttypmod),
                  'notnull', a.attnotnull,
                  'generated', (a.attgenerated <> '' or a.attidentity <> ''),
                  'pk', coalesce(a.attnum = any(i.indkey), false))
                order by a.attnum)
         from pg_attribute a
         where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
       ), '[]'::json) as columns
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
left join pg_index i on i.indrelid = c.oid and i.indisprimary
where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm')
order by c.relname`

/** Tables whose rows the Tables page never edits: identifier ledgers, append-only history, secrets. */
export const READ_ONLY_TABLES = new Set([
  'pcid_blocks',
  'pcid_retired',
  'entity_versions',
  'entity_changes',
  'api_meta',
  'ingest_tokens',
])

export const quoteIdent = (name: string): string => `"${name.replace(/"/g, '""')}"`

const TEXT_LIKE = /^(text|character|character varying|citext|uuid|json|jsonb)\b/

export function isEditableTable(t: TableMeta): boolean {
  return (t.kind === 'r' || t.kind === 'p') && !READ_ONLY_TABLES.has(t.name) && t.columns.some(c => c.pk)
}

/** Why a column can't be edited, or null when it can. */
export function lockReason(t: TableMeta, c: ColumnMeta): string | null {
  if (t.kind === 'v' || t.kind === 'm') return 'Derived (view): fix the source tables and refresh.'
  if (READ_ONLY_TABLES.has(t.name)) return 'This table is an identifier ledger, history or secret: read-only here.'
  if (!t.columns.some(col => col.pk)) return 'The table has no primary key, so a row cannot be addressed safely.'
  if (c.pk) return 'Part of the row key: never changed here.'
  if (c.name === 'pcid') return 'A PCID is permanent.'
  if (c.generated) return 'Generated by the database.'
  return null
}

export interface RowsParams {
  limit: number
  offset: number
  sort?: string
  dir: 'asc' | 'desc'
  q?: string
  filters: Record<string, string>
}

export const MAX_LIMIT = 500
export const MAX_CSV_ROWS = 100_000

/** Reads list parameters from a query string; anything unknown or out of range falls back. */
export function parseRowsParams(sp: URLSearchParams, t: TableMeta, csv = false): RowsParams {
  const names = new Set(t.columns.map(c => c.name))
  const cap = csv ? MAX_CSV_ROWS : MAX_LIMIT
  const limit = Math.min(cap, Math.max(1, Number(sp.get('limit')) || (csv ? cap : 100)))
  const offset = Math.max(0, Math.floor(Number(sp.get('offset')) || 0))
  const sortRaw = sp.get('sort') ?? undefined
  const sort = sortRaw && names.has(sortRaw) ? sortRaw : undefined
  const dir = sp.get('dir') === 'desc' ? 'desc' : 'asc'
  const q = (sp.get('q') ?? '').trim() || undefined
  const filters: Record<string, string> = {}
  for (const [k, v] of sp) {
    if (k.startsWith('f.') && names.has(k.slice(2)) && v.trim() !== '') filters[k.slice(2)] = v.trim()
  }
  return { limit, offset, sort, dir, q, filters }
}

const escapeLike = (s: string): string => s.replace(/[\\%_]/g, m => '\\' + m)

/** WHERE clause and its parameters (shared by the row, count and CSV queries). */
export function buildWhere(t: TableMeta, p: RowsParams): { sql: string; values: string[] } {
  const parts: string[] = []
  const values: string[] = []
  for (const [name, raw] of Object.entries(p.filters)) {
    const col = t.columns.find(c => c.name === name)
    if (!col) continue
    const ident = quoteIdent(name)
    if (raw === '∅' || raw.toLowerCase() === 'null') {
      parts.push(`${ident} is null`)
    } else if (TEXT_LIKE.test(col.type) || col.type.endsWith('[]')) {
      values.push(`%${escapeLike(raw)}%`)
      parts.push(`${ident}::text ilike $${values.length}`)
    } else {
      values.push(raw)
      parts.push(`${ident}::text = $${values.length}`)
    }
  }
  if (p.q) {
    values.push(`%${escapeLike(p.q)}%`)
    const n = values.length
    parts.push('(' + t.columns.map(c => `${quoteIdent(c.name)}::text ilike $${n}`).join(' or ') + ')')
  }
  return { sql: parts.length ? ' where ' + parts.join(' and ') : '', values }
}

export function buildRowsQuery(t: TableMeta, p: RowsParams): { text: string; values: string[] } {
  const where = buildWhere(t, p)
  const pk = t.columns.filter(c => c.pk).map(c => quoteIdent(c.name))
  const order = p.sort
    ? `${quoteIdent(p.sort)} ${p.dir} nulls last` + (pk.length ? ', ' + pk.join(', ') : '')
    : pk.join(', ')
  const text =
    `select * from public.${quoteIdent(t.name)}${where.sql}` +
    (order ? ` order by ${order}` : '') +
    ` limit ${p.limit} offset ${p.offset}`
  return { text, values: where.values }
}

export function buildCountQuery(t: TableMeta, p: RowsParams): { text: string; values: string[] } {
  const where = buildWhere(t, p)
  return { text: `select count(*)::bigint as n from public.${quoteIdent(t.name)}${where.sql}`, values: where.values }
}

export interface UpdateRequest {
  table: string
  key: Record<string, unknown>
  column: string
  oldValue: unknown
  newValue: unknown
}

/** Checks an edit against the catalogue. Returns an error message, or null when it may go ahead. */
export function checkUpdate(t: TableMeta | undefined, u: UpdateRequest): string | null {
  if (!t) return 'Unknown table.'
  const col = t.columns.find(c => c.name === u.column)
  if (!col) return 'Unknown column.'
  const reason = lockReason(t, col)
  if (reason) return reason
  const pk = t.columns.filter(c => c.pk).map(c => c.name)
  const given = Object.keys(u.key ?? {})
  if (given.length !== pk.length || !pk.every(k => given.includes(k))) return 'The row key does not match the table.'
  if (pk.some(k => u.key[k] === null || u.key[k] === undefined)) return 'The row key is incomplete.'
  if (col.notnull && u.newValue === null) return `${col.name} cannot be empty (NOT NULL).`
  return null
}

/** Key condition `"a"::text = $1 and "b"::text = $2` with values as text (bigints arrive as strings). */
export function keyCondition(t: TableMeta, key: Record<string, unknown>, firstParam: number): { sql: string; values: string[] } {
  const pk = t.columns.filter(c => c.pk).map(c => c.name)
  return {
    sql: pk.map((k, i) => `${quoteIdent(k)}::text = $${firstParam + i}`).join(' and '),
    values: pk.map(k => String(key[k])),
  }
}

/** The value as Postgres should receive it for a column of this type. */
export function toParam(type: string, v: unknown): unknown {
  if (v === null || v === undefined) return null
  if (type.endsWith('[]')) {
    if (Array.isArray(v)) return v
    const s = String(v).trim()
    if (s.startsWith('[')) return JSON.parse(s) as unknown
    return s // Postgres array literal, e.g. {a,b}
  }
  if (/^jsonb?\b/.test(type)) return typeof v === 'string' ? v : JSON.stringify(v)
  return typeof v === 'string' ? v : String(v)
}

/** Same value? Compared as the JSON the browser saw (dates as ISO strings, bigints as strings). */
export const sameValue = (a: unknown, b: unknown): boolean => JSON.stringify(a ?? null) === JSON.stringify(b ?? null)

export function toCsv(columns: string[], rows: Record<string, unknown>[]): string {
  const cell = (v: unknown): string => {
    if (v === null || v === undefined) return ''
    const s = v instanceof Date ? v.toISOString() : typeof v === 'object' ? JSON.stringify(v) : String(v)
    return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
  }
  return [columns.map(cell).join(','), ...rows.map(r => columns.map(c => cell(r[c])).join(','))].join('\r\n') + '\r\n'
}
