/** Columns whose values stay hidden until asked for (tokens, secrets). */
export const isSecret = (column: string): boolean => /token|secret|password/i.test(column)

/** A PCID column holding a PCID number → its permalink. */
export function pcidHref(column: string, value: unknown): string | null {
  if (!/(^|_)pcid$/.test(column)) return null
  const s = String(value ?? '')
  return /^\d{7,8}$/.test(s) ? `/id/PCID-${s}` : null
}

/** Text for one cell, cut to `max` characters. */
export function cellText(v: unknown, max = 80): string {
  if (v === null || v === undefined) return 'NULL'
  const s = typeof v === 'object' ? JSON.stringify(v) : String(v)
  return s.length > max ? s.slice(0, max - 1) + '…' : s
}

/** The text put in the edit box for a value. */
export function editText(v: unknown): string {
  if (v === null || v === undefined) return ''
  return typeof v === 'object' ? JSON.stringify(v, null, 2) : String(v)
}

/** Parses what was typed into the value sent to the server for a column of this type. */
export function parseEdit(type: string, text: string, isNull: boolean): unknown {
  if (isNull) return null
  if (type.endsWith('[]') || /^jsonb?\b/.test(type)) {
    const s = text.trim()
    if (/^jsonb?\b/.test(type)) {
      JSON.parse(s) // throws on invalid JSON, shown to the user
      return s
    }
    return s.startsWith('[') ? (JSON.parse(s) as unknown) : s
  }
  if (type === 'boolean') {
    const s = text.trim().toLowerCase()
    if (!['true', 'false'].includes(s)) throw new Error('Type true or false.')
    return s
  }
  return text
}

export const formatCount = (n: number): string => n.toLocaleString('en-US')
