export interface ColumnMeta {
  name: string
  type: string
  notnull: boolean
  generated: boolean
  pk: boolean
}

export interface TableMeta {
  name: string
  kind: 'r' | 'p' | 'v' | 'm'
  estimate: number
  comment: string | null
  columns: ColumnMeta[]
}

export type Row = Record<string, unknown>

export interface RowsPage {
  rows: Row[]
  total: number | null
  estimate: number
  limit: number
  offset: number
}

const BASE = '/__local/db'

async function call<T>(path: string, init?: RequestInit): Promise<T> {
  const r = await fetch(BASE + path, init)
  const body = (await r.json().catch(() => ({}))) as T & { error?: string }
  if (!r.ok) throw new Error(body.error ?? `HTTP ${r.status}`)
  return body
}

let tablesCache: Promise<TableMeta[]> | null = null
export function loadTables(fresh = false): Promise<TableMeta[]> {
  if (fresh || !tablesCache) {
    tablesCache = call<{ tables: TableMeta[] }>('/tables' + (fresh ? '?fresh=1' : '')).then(b => b.tables)
    tablesCache.catch(() => { tablesCache = null })
  }
  return tablesCache
}

export function loadRows(table: string, params: URLSearchParams): Promise<RowsPage> {
  const sp = new URLSearchParams(params)
  sp.set('table', table)
  return call<RowsPage>('/rows?' + sp.toString())
}

export function csvUrl(table: string, params: URLSearchParams): string {
  const sp = new URLSearchParams(params)
  sp.set('table', table)
  sp.delete('offset')
  sp.delete('limit')
  return `${BASE}/csv?${sp.toString()}`
}

export function saveCell(req: { table: string; key: Row; column: string; oldValue: unknown; newValue: unknown }): Promise<{ value: unknown }> {
  return call('/update', {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-pc-local': '1' },
    body: JSON.stringify(req),
  })
}

// ─── Grouping ────────────────────────────────────────────────────────────────

export const GROUPS = [
  'Records',
  'Relationships',
  'Lists',
  'Labels',
  'Sources',
  'Learn',
  'Community (dormant)',
  'History',
  'Bookkeeping',
  'Derived views',
  'Other',
] as const
export type Group = (typeof GROUPS)[number]

const RECORDS = new Set([
  'entities', 'moieties', 'combinations', 'precise_forms', 'formulations', 'drug_classes',
  'clinical_concepts', 'measurements', 'biological_targets', 'functional_groups',
])
const RELATIONSHIPS = new Set(['clinical_statements', 'class_members', 'predicates', 'community_statements', 'entity_guidelines'])
const HISTORY = new Set(['entity_versions', 'entity_changes', 'revisions'])
const BOOKKEEPING = new Set([
  'pcid_blocks', 'pcid_retired', 'api_meta', 'ingest_tokens', 'data_sources', 'class_rules',
  'class_search_aliases', 'class_agent_review', 'block_schemas', 'page_templates', 'section_embeds', 'threshold_rules',
])
const COMMUNITY = /^(page_|infobox_|contributor_|community_pages|brand_edits|blog_comments|user_roles|saved_entities|provider_verifications|account_profiles|citation_sources)/

/** Which heading a table is listed under on the Tables page. */
export function groupOf(t: Pick<TableMeta, 'name' | 'kind'>): Group {
  if (t.kind === 'v' || t.kind === 'm') return 'Derived views'
  const n = t.name
  if (RECORDS.has(n)) return 'Records'
  if (RELATIONSHIPS.has(n)) return 'Relationships'
  if (n === 'lists' || n === 'list_items') return 'Lists'
  if (n.startsWith('label_')) return 'Labels'
  if (n.startsWith('learn_')) return 'Learn'
  if (HISTORY.has(n)) return 'History'
  if (BOOKKEEPING.has(n)) return 'Bookkeeping'
  if (COMMUNITY.test(n)) return 'Community (dormant)'
  if (/^(fda_|rxnorm_|rxclass_|chemont_|classyfire_|rems_|physiochemical|dictionary_|federal_|lasa_|references_|guidelines|term_definitions|structure_|product_packaging)/.test(n)) return 'Sources'
  return 'Other'
}

// ─── Editing rules (mirror scripts/localDb.ts lockReason; the server checks again) ──

export const READ_ONLY_TABLES = new Set(['pcid_blocks', 'pcid_retired', 'entity_versions', 'entity_changes', 'api_meta', 'ingest_tokens'])

export function lockReason(t: TableMeta, c: ColumnMeta): string | null {
  if (t.kind === 'v' || t.kind === 'm') return 'Derived (view): fix the source tables and refresh.'
  if (READ_ONLY_TABLES.has(t.name)) return 'This table is an identifier ledger, history or secret: read-only here.'
  if (!t.columns.some(col => col.pk)) return 'The table has no primary key, so a row cannot be addressed safely.'
  if (c.pk) return 'Part of the row key: never changed here.'
  if (c.name === 'pcid') return 'A PCID is permanent.'
  if (c.generated) return 'Generated by the database.'
  return null
}

